from pathlib import Path
import joblib
import numpy as np
import pandas as pd

from sklearn.model_selection import KFold, cross_val_predict
from sklearn.compose import ColumnTransformer
from sklearn.preprocessing import OneHotEncoder, StandardScaler
from sklearn.pipeline import Pipeline
from sklearn.linear_model import LinearRegression
from sklearn.metrics import (
    mean_absolute_error,
    mean_squared_error,
    r2_score
)

BASE = Path(__file__).resolve().parent.parent
DATA_FILE = BASE / "datasets" / "raw" / "revenue" / "train.csv"
MODEL_DIR = BASE / "models"
RESULT_DIR = BASE / "results"

MODEL_DIR.mkdir(exist_ok=True)
RESULT_DIR.mkdir(exist_ok=True)

print("=" * 55)
print("DINEMIND AI - RESTAURANT REVENUE PREDICTION")
print("=" * 55)

# STEP 1: LOAD DATA

print("\n[1/6] Loading dataset...", flush=True)

data = pd.read_csv(DATA_FILE)

print("Records:", len(data))
print("Missing values:", data.isna().sum().sum())

# STEP 2: FEATURE ENGINEERING

print("\n[2/6] Preparing restaurant features...")

data["Open Date"] = pd.to_datetime(
    data["Open Date"],
    format="%m/%d/%Y",
    errors="raise"
)

data["opening_year"] = data["Open Date"].dt.year
data["opening_month"] = data["Open Date"].dt.month

# Use a small predefined subset of P-features.
# They are anonymized by the dataset provider.
numeric_features = [
    "opening_year",
    "opening_month",
    "P1", "P2", "P3", "P4", "P5"
]

categorical_features = [
    "City Group",
    "Type"
]

features = numeric_features + categorical_features

X = data[features].copy()
y = data["revenue"].astype(float)

assert X.notna().all().all()
assert y.notna().all()
assert np.isfinite(y).all()

print("Input features:", features)
print("Revenue observations:", len(y))

# STEP 3: BUILD LINEAR REGRESSION PIPELINE

print("\n[3/6] Building Linear Regression...", flush=True)

preprocessor = ColumnTransformer([
    (
        "numeric",
        StandardScaler(),
        numeric_features
    ),
    (
        "categorical",
        OneHotEncoder(
            handle_unknown="ignore",
            sparse_output=False
        ),
        categorical_features
    )
])

model = Pipeline([
    ("preprocessor", preprocessor),
    ("regressor", LinearRegression())
])

# STEP 4: CROSS-VALIDATION

print("\n[4/6] Running 5-fold cross-validation...", flush=True)

cv = KFold(
    n_splits=5,
    shuffle=True,
    random_state=42
)

# Every prediction is generated by a model
# that did not train on that restaurant.
predictions = cross_val_predict(
    model, X, y, cv=cv
)

# Revenue cannot be negative.
predictions = np.maximum(predictions, 0)

mae = mean_absolute_error(y, predictions)
rmse = np.sqrt(mean_squared_error(y, predictions))
r2 = r2_score(y, predictions)

# A fold-wise mean baseline.
# Each validation row gets the mean of
# the corresponding training fold.
baseline_predictions = np.empty(len(y))

for fit_idx, val_idx in cv.split(X):
    baseline_mean = y.iloc[fit_idx].mean()
    baseline_predictions[val_idx] = baseline_mean

baseline_mae = mean_absolute_error(
    y, baseline_predictions
)
baseline_rmse = np.sqrt(
    mean_squared_error(y, baseline_predictions)
)

print("\n" + "=" * 55)
print("LINEAR REGRESSION REVENUE RESULTS")
print("=" * 55)

print(f"MAE:  {mae:,.4f}")
print(f"RMSE: {rmse:,.4f}")
print(f"R²:   {r2:.4f}")

print("\nBASELINE COMPARISON")
print(f"Mean baseline MAE: {baseline_mae:,.4f}")
print(f"Linear Regression MAE: {mae:,.4f}")
print(f"Mean baseline RMSE: {baseline_rmse:,.4f}")

if mae < baseline_mae:
    print("Linear Regression beats the MAE baseline.")
else:
    print("The mean baseline performs as well or better.")

# STEP 5: TRAIN FINAL MODEL

print("\n[5/6] Training final model...", flush=True)

# Cross-validation is complete.
# Now fit on all available labeled data
# for use in the demonstration website.
model.fit(X, y)

model_path = (
    MODEL_DIR / "linear_regression_revenue_model.joblib"
)

joblib.dump(
    model,
    model_path
)

# STEP 6: SAVE RESULTS

print("\n[6/6] Saving results...", flush=True)

metrics = pd.DataFrame([{
    "model": "Linear Regression Revenue",
    "records": len(data),
    "evaluation": "5-fold out-of-fold",
    "mae": mae,
    "rmse": rmse,
    "r2": r2,
    "baseline_mae": baseline_mae,
    "baseline_rmse": baseline_rmse
}])

metrics.to_csv(
    RESULT_DIR / "linear_regression_revenue_metrics.csv",
    index=False
)

results = pd.DataFrame({
    "restaurant_id": data["Id"],
    "actual_revenue": y,
    "predicted_revenue": predictions,
    "absolute_error": np.abs(y - predictions)
})

results.to_csv(
    RESULT_DIR / "linear_regression_revenue_results.csv",
    index=False
)

# Sample model prediction using an
# existing restaurant's input attributes.
sample = X.iloc[[0]]
sample_prediction = float(model.predict(sample)[0])

print("\nSAMPLE PREDICTION")
print("-" * 40)
print("Restaurant ID:", data.iloc[0]["Id"])
print("Predicted revenue value:",
      f"{max(0, sample_prediction):,.2f}")

print("\nNote: This sample was used in final fitting.")
print("It is a functionality test, not a")
print("held-out performance evaluation.")
print("Revenue units are anonymized.")

print("\n" + "=" * 55)
print("ML-01 REVENUE MODEL COMPLETED!")
print("=" * 55)

print("\nSaved files:")
print("models/linear_regression_revenue_model.joblib")
print("results/linear_regression_revenue_metrics.csv")
print("results/linear_regression_revenue_results.csv")
